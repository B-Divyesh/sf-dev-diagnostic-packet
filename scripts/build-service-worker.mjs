import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const siteRoot = 'dist/site';
const ignored = new Set(['sw.js', 'staticwebapp.config.json']);

function filesAt(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = join(directory, entry.name);
    return entry.isDirectory() ? filesAt(file) : [file];
  });
}

function sourceFile(path) {
  if (path === '/') return join(siteRoot, 'index.html');
  return join(siteRoot, path.slice(1), path.endsWith('/') ? 'index.html' : '');
}

const shell = filesAt(siteRoot)
  .map((file) => relative(siteRoot, file).replaceAll('\\', '/'))
  .filter((file) => !ignored.has(file))
  .map((file) => {
    if (file === 'index.html') return '/';
    if (file.endsWith('/index.html')) return `/${file.slice(0, -'index.html'.length)}`;
    return `/${file}`;
  })
  .sort();

const version = createHash('sha256')
  .update(shell.map((path) => `${path}:${readFileSync(sourceFile(path))}`).join('\n'))
  .digest('hex')
  .slice(0, 12);

const worker = `/* Generated by scripts/build-service-worker.mjs. Do not edit. */
const CACHE = 'diagnostic-packet-${version}';
const SHELL = ${JSON.stringify(shell)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});

const fromCache = (request) => caches.match(request, { ignoreVary: true });

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET' || new URL(event.request.url).origin !== self.location.origin) return;
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => fromCache(event.request).then((cached) => cached || caches.match('/'))));
    return;
  }
  event.respondWith(fromCache(event.request).then((cached) => cached || fetch(event.request)));
});
`;

writeFileSync(join(siteRoot, 'sw.js'), worker);
console.log(`Generated sw.js with ${shell.length} precached files (diagnostic-packet-${version}).`);
